import {test,expect} from '@playwright/test'
import {createServer} from 'node:http'
import {randomUUID} from 'node:crypto'

test('personal learning persists and the floating advisor plans from own history',async({page})=>{
 const requests=[]
 const model=createServer(async(req,res)=>{
  let body='';for await(const chunk of req)body+=chunk
  requests.push(JSON.parse(body));res.setHeader('Content-Type','application/json')
  res.end(JSON.stringify({choices:[{message:{content:'[测试模型] 明日目标：复习二分不变量，20 分钟边界分析，25 分钟练习。'}}]}))
 })
 await new Promise(resolve=>model.listen(0,'127.0.0.1',resolve))
 try {
  await page.goto('/')
  await page.getByRole('button',{name:'登录 / 注册',exact:true}).click()
  await page.getByRole('button',{name:'还没有账号？注册'}).click()
  await page.getByLabel('邮箱',{exact:true}).fill(`learning-${randomUUID()}@example.com`)
  await page.getByLabel('密码',{exact:true}).fill(`Learning-${randomUUID()}`)
  await page.getByLabel('昵称',{exact:true}).fill('打卡测试同伴')
  await page.locator('.dialog').getByRole('button',{name:'确认',exact:true}).click()
  await page.getByRole('button',{name:'用户菜单'}).click()
  await page.getByRole('button',{name:'⚙ 个人设置',exact:true}).click()
  await page.getByLabel('模型接口地址').fill(`http://127.0.0.1:${model.address().port}/model`)
  await page.getByLabel('顾问模型名称').fill('fixture-model')
  await page.getByLabel('顾问 API 密钥').fill('browser-fixture-secret')
  await page.getByRole('button',{name:'保存连接设置'}).click()
  await page.getByRole('button',{name:'✓ 每日学习',exact:true}).click()
  await page.getByLabel('Codeforces 用户名').fill('tourist')
  await page.getByRole('button',{name:'保存绑定',exact:true}).click()
  await expect(page.getByText('已绑定：tourist',{exact:true})).toBeVisible()
  await page.getByLabel('知识点目标').fill('二分不变量')
  await page.getByLabel('Codeforces 题号').fill('4A')
  await page.getByLabel('理解检查标准').fill('解释边界和复杂度')
  await page.getByRole('button',{name:'保存学习点',exact:true}).click()
  await page.getByRole('combobox',{name:'学习点',exact:true}).selectOption({label:'二分不变量 · 4A'})
  await page.getByLabel('实际学习分钟').fill('30')
  await page.getByLabel('复盘与困难').fill('循环边界仍不清楚')
  await page.getByRole('button',{name:'提交今日打卡',exact:true}).click()
  await expect(page.getByText('循环边界仍不清楚',{exact:true})).toBeVisible()
  await expect(page.getByRole('button',{name:'结算本日',exact:true})).toBeDisabled()
  await page.getByRole('button',{name:'根据打卡规划明日目标'}).click()
  const popup=page.getByRole('region',{name:'机器人快捷窗口'})
  await expect(popup).toBeVisible()
  await popup.getByRole('checkbox').check()
  await popup.getByRole('button',{name:'生成明日目标',exact:true}).click()
  await expect(popup).toContainText('[测试模型] 明日目标')
  expect(requests[0].messages.at(-1).content).toContain('循环边界仍不清楚')
  expect(JSON.stringify(requests)).not.toContain('browser-fixture-secret')
  await popup.getByRole('button',{name:'保存为明日目标',exact:true}).click()
  await expect(popup.getByRole('button',{name:'已保存，可在每日学习页刷新查看'})).toBeDisabled()
  await popup.getByRole('button',{name:'关闭顾问'}).click()
  await page.reload()
  await page.getByRole('button',{name:'✓ 每日学习',exact:true}).click()
  await expect(page.getByText('[测试模型] 明日目标：复习二分不变量，20 分钟边界分析，25 分钟练习。',{exact:true})).toBeVisible()
  await expect(page.getByText('循环边界仍不清楚',{exact:true})).toBeVisible()
  await page.screenshot({path:'test-results/learning-desktop.png',fullPage:true})
  await page.setViewportSize({width:390,height:844})
  await page.getByRole('button',{name:'快速询问机器人'}).click()
  await expect(popup).toBeVisible()
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 } finally {await new Promise(resolve=>model.close(resolve))}
})
