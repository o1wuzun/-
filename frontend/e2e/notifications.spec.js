import {test,expect} from '@playwright/test'
import {randomUUID} from 'node:crypto'
test('requester receives approval feedback and can mark it read',async({browser})=>{
 test.setTimeout(120000)
 test.skip(!process.env.TEST_ADMIN_EMAIL||!process.env.TEST_ADMIN_PASSWORD,'Local administrator credentials required')
 const memberContext=await browser.newContext(),adminContext=await browser.newContext()
 try{
  const member=await memberContext.newPage(),admin=await adminContext.newPage()
  await member.goto('http://127.0.0.1:5173')
  await member.getByRole('button',{name:'登录 / 注册',exact:true}).click()
  await member.getByRole('button',{name:'还没有账号？注册'}).click()
  await member.getByLabel('邮箱',{exact:true}).fill(`notice-browser-${randomUUID()}@example.test`)
  await member.getByLabel('密码',{exact:true}).fill('Browser-test-123')
  await member.getByLabel('昵称',{exact:true}).fill('通知测试成员')
  await member.getByRole('button',{name:'确认',exact:true}).click()
  await expect(member.locator('header')).toContainText('通知测试成员')
  await member.getByRole('button',{name:'◇ 群组入口',exact:true}).click()
  await member.getByRole('button',{name:'＋ 创建群组',exact:true}).click()
  const name=`审批反馈-${randomUUID()}`
  await member.getByLabel('群组名称',{exact:true}).fill(name)
  await member.getByLabel('群组简介',{exact:true}).fill('测试普通用户申请与审批结果通知')
  await member.getByRole('combobox',{name:'群组类型',exact:true}).selectOption('PRIVATE')
  await member.locator('.dialog').getByRole('button',{name:'确认',exact:true}).click()
  await expect(member.locator('.dialog')).not.toBeVisible()
  await member.getByRole('button',{name:'用户菜单',exact:true}).click()
  await member.getByRole('button',{name:'消息与申请',exact:true}).click()
  await expect(member.locator('.member').filter({hasText:name})).toContainText('待审批')
  await admin.goto('http://127.0.0.1:5173')
  await admin.getByRole('button',{name:'登录 / 注册',exact:true}).click()
  await admin.getByLabel('邮箱',{exact:true}).fill(process.env.TEST_ADMIN_EMAIL)
  await admin.getByLabel('密码',{exact:true}).fill(process.env.TEST_ADMIN_PASSWORD)
  await admin.getByRole('button',{name:'确认',exact:true}).click()
  await admin.getByRole('button',{name:'管理后台',exact:true}).click()
  const row=admin.locator('.member').filter({hasText:name})
  await row.getByRole('button',{name:'批准',exact:true}).click()
  await expect(row).toContainText('APPROVED')
  await member.getByRole('button',{name:'刷新消息',exact:true}).click()
  const notice=member.locator('article').filter({has:member.getByRole('heading',{name:'群组创建申请已批准',exact:true})})
  await expect(notice).toContainText('批准不代表群组已经可连接')
  await notice.getByRole('button',{name:'标记已读',exact:true}).click()
  await expect(notice).toContainText('已读')
  await member.reload()
  await member.getByRole('button',{name:'用户菜单',exact:true}).click()
  await member.getByRole('button',{name:'消息与申请',exact:true}).click()
  const application=member.locator('.member').filter({hasText:name})
  await expect(application).toContainText('已批准')
  await application.getByRole('button',{name:'一键部署本地群组',exact:true}).click()
  await expect(application).toContainText('已部署',{timeout:90000})
  await application.getByRole('button',{name:'查看加入密钥',exact:true}).click()
  const joinKey=await application.locator('code').textContent()
  expect(joinKey.length).toBeGreaterThanOrEqual(16)
  await member.screenshot({path:test.info().outputPath('notifications-desktop.png'),fullPage:true})
  await member.setViewportSize({width:390,height:844})
  await expect.poll(()=>member.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true)
  await member.setViewportSize({width:1366,height:900})
  await member.getByRole('button',{name:'◇ 群组入口',exact:true}).click()
  const groupCard=member.locator('article').filter({has:member.getByRole('heading',{name,exact:true})})
  await groupCard.getByRole('button').click()
  await member.locator('.dialog').getByLabel('群主分享的联网密钥').fill(joinKey)
  await member.locator('.dialog').getByRole('button',{name:'确认',exact:true}).click()
  await member.getByRole('button',{name:'⌂ 概览',exact:true}).click()
  await expect(member.locator('h1')).toHaveText(name)
  await expect(member.locator('.group-home')).toContainText('私密群组')
  await expect(member.getByRole('heading',{name:'群主邀请管理'})).toBeVisible()
  await member.getByRole('button',{name:'查看加入密钥',exact:true}).click()
  await expect(member.getByLabel('群组加入密钥',{exact:true})).toHaveValue(joinKey)
  await member.reload()
  await expect(member.locator('.group-home')).toBeVisible()
 }finally{await memberContext.close();await adminContext.close()}
})
