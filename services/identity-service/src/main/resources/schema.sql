CREATE TABLE IF NOT EXISTS accounts (
 id VARCHAR(36) PRIMARY KEY,
 email VARCHAR(200) NOT NULL UNIQUE,
 nickname VARCHAR(40) NOT NULL,
 password_hash VARCHAR(100) NOT NULL
);
ALTER TABLE accounts ADD COLUMN IF NOT EXISTS avatar_url VARCHAR(500);
ALTER TABLE accounts ADD COLUMN IF NOT EXISTS role VARCHAR(20) DEFAULT 'USER';
CREATE TABLE IF NOT EXISTS user_settings (
 user_id VARCHAR(36) PRIMARY KEY,
 oj_provider VARCHAR(40), oj_api_key VARCHAR(500),
 advisor_provider VARCHAR(40), advisor_api_key VARCHAR(500),
 CONSTRAINT fk_user_settings_account FOREIGN KEY (user_id) REFERENCES accounts(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS group_requests (
 id VARCHAR(36) PRIMARY KEY, requested_by VARCHAR(36) NOT NULL,
 name VARCHAR(80) NOT NULL, description VARCHAR(500) NOT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'PENDING', created_at VARCHAR(40) NOT NULL,
 visibility VARCHAR(10) NOT NULL DEFAULT 'PUBLIC',
 deployment_status VARCHAR(20) NOT NULL DEFAULT 'NOT_DEPLOYED', deployed_at VARCHAR(40),
 CONSTRAINT fk_group_requests_user FOREIGN KEY (requested_by) REFERENCES accounts(id)
);
CREATE TABLE IF NOT EXISTS advisor_turns (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id VARCHAR(36) NOT NULL, group_id VARCHAR(80) NOT NULL,
 question VARCHAR(4000) NOT NULL, answer CLOB NOT NULL, created_at VARCHAR(40) NOT NULL,
 FOREIGN KEY(user_id) REFERENCES accounts(id)
);

ALTER TABLE user_settings ADD COLUMN IF NOT EXISTS advisor_endpoint VARCHAR(1000);
CREATE TABLE IF NOT EXISTS advisor_generations (
 user_id VARCHAR(36) NOT NULL, group_id VARCHAR(80) NOT NULL, generation BIGINT NOT NULL DEFAULT 0,
 PRIMARY KEY(user_id,group_id)
);
CREATE TABLE IF NOT EXISTS public_access_policy (
 id INT PRIMARY KEY, enabled BOOLEAN NOT NULL DEFAULT FALSE, generation BIGINT NOT NULL DEFAULT 0
);
INSERT INTO public_access_policy(id,enabled,generation) SELECT 1,FALSE,0 WHERE NOT EXISTS(SELECT 1 FROM public_access_policy WHERE id=1);
CREATE TABLE IF NOT EXISTS public_access_invites (
 id VARCHAR(36) PRIMARY KEY, name VARCHAR(80) NOT NULL, token_hash VARCHAR(64) NOT NULL UNIQUE,
 expires_at BIGINT NOT NULL, created_at BIGINT NOT NULL, consumed BOOLEAN NOT NULL, revoked BOOLEAN NOT NULL
);
CREATE TABLE IF NOT EXISTS public_access_sessions (
 token_hash VARCHAR(64) PRIMARY KEY, invite_id VARCHAR(36) NOT NULL, generation BIGINT NOT NULL, expires_at BIGINT NOT NULL,
 FOREIGN KEY(invite_id) REFERENCES public_access_invites(id)
);

CREATE TABLE IF NOT EXISTS notifications (
 id VARCHAR(36) PRIMARY KEY, user_id VARCHAR(36) NOT NULL, request_id VARCHAR(36) NOT NULL UNIQUE,
 title VARCHAR(200) NOT NULL, body VARCHAR(2000) NOT NULL, created_at VARCHAR(40) NOT NULL, is_read BOOLEAN NOT NULL DEFAULT FALSE, delivered_at VARCHAR(30),
 FOREIGN KEY(user_id) REFERENCES accounts(id), FOREIGN KEY(request_id) REFERENCES group_requests(id)
);
CREATE INDEX IF NOT EXISTS idx_notifications_user ON notifications(user_id,created_at);
CREATE TABLE IF NOT EXISTS mail_jobs (
 id VARCHAR(36) PRIMARY KEY, notification_id VARCHAR(36) NOT NULL UNIQUE,
 recipient VARCHAR(200) NOT NULL, subject VARCHAR(200) NOT NULL, body VARCHAR(2000) NOT NULL,
 status VARCHAR(30) NOT NULL, attempts INT NOT NULL DEFAULT 0, publish_attempts INT NOT NULL DEFAULT 0,
 next_attempt_at BIGINT NOT NULL DEFAULT 0, last_error VARCHAR(500), created_at VARCHAR(40) NOT NULL, sent_at VARCHAR(40),
 FOREIGN KEY(notification_id) REFERENCES notifications(id)
);
CREATE INDEX IF NOT EXISTS idx_mail_jobs_due ON mail_jobs(status,next_attempt_at);
ALTER TABLE group_requests ADD COLUMN IF NOT EXISTS deployment_error VARCHAR(300);
ALTER TABLE group_requests ADD COLUMN IF NOT EXISTS visibility VARCHAR(10) NOT NULL DEFAULT 'PUBLIC';
ALTER TABLE group_requests ADD COLUMN IF NOT EXISTS deployment_status VARCHAR(20) NOT NULL DEFAULT 'NOT_DEPLOYED';
ALTER TABLE group_requests ADD COLUMN IF NOT EXISTS deployed_at VARCHAR(40);
ALTER TABLE notifications ADD COLUMN IF NOT EXISTS delivered_at VARCHAR(30);
CREATE TABLE IF NOT EXISTS deployed_groups (
 id VARCHAR(80) PRIMARY KEY, request_id VARCHAR(36) NOT NULL UNIQUE, owner_id VARCHAR(36) NOT NULL,
 name VARCHAR(80) NOT NULL, description VARCHAR(500) NOT NULL, visibility VARCHAR(10) NOT NULL,
 port INT NOT NULL UNIQUE, join_key VARCHAR(100) NOT NULL, status VARCHAR(20) NOT NULL
);
CREATE TABLE IF NOT EXISTS oj_bindings (
 user_id VARCHAR(36) PRIMARY KEY, provider VARCHAR(30) NOT NULL, handle VARCHAR(80) NOT NULL, version BIGINT NOT NULL,
 FOREIGN KEY(user_id) REFERENCES accounts(id)
);
CREATE TABLE IF NOT EXISTS learning_points (
 id VARCHAR(36) PRIMARY KEY, user_id VARCHAR(36) NOT NULL, title VARCHAR(100) NOT NULL,
 problem_key VARCHAR(40) NOT NULL, criterion VARCHAR(500) NOT NULL, created_at VARCHAR(40) NOT NULL,
 FOREIGN KEY(user_id) REFERENCES accounts(id)
);
CREATE TABLE IF NOT EXISTS daily_checkins (
 id VARCHAR(36) PRIMARY KEY, user_id VARCHAR(36) NOT NULL, learning_day VARCHAR(10) NOT NULL,
 point_id VARCHAR(36) NOT NULL, minutes INT NOT NULL, reflection VARCHAR(2000) NOT NULL,
 verification VARCHAR(30) NOT NULL, evidence_id VARCHAR(80), evidence_handle VARCHAR(80), binding_version BIGINT,
 settled BOOLEAN NOT NULL DEFAULT FALSE, score INT NOT NULL DEFAULT 0, created_at VARCHAR(40) NOT NULL,
 UNIQUE(user_id,learning_day),
 FOREIGN KEY(user_id) REFERENCES accounts(id), FOREIGN KEY(point_id) REFERENCES learning_points(id)
);
CREATE TABLE IF NOT EXISTS learning_awards (
 user_id VARCHAR(36) NOT NULL, problem_key VARCHAR(40) NOT NULL, checkin_id VARCHAR(36) NOT NULL,
 PRIMARY KEY(user_id,problem_key),
 FOREIGN KEY(user_id) REFERENCES accounts(id), FOREIGN KEY(checkin_id) REFERENCES daily_checkins(id)
);
CREATE INDEX IF NOT EXISTS idx_learning_points_user ON learning_points(user_id,created_at);
CREATE TABLE IF NOT EXISTS learning_plans (
 user_id VARCHAR(36) NOT NULL, learning_day VARCHAR(10) NOT NULL,
 body TEXT NOT NULL, created_at VARCHAR(40) NOT NULL,
 PRIMARY KEY(user_id,learning_day), FOREIGN KEY(user_id) REFERENCES accounts(id)
);
