package dev.algotogether.identity;

import com.fasterxml.jackson.databind.ObjectMapper;
import com.sun.net.httpserver.HttpServer;
import dev.algotogether.contracts.TokenCodec;
import java.net.InetSocketAddress;
import java.security.KeyPairGenerator;
import java.util.Base64;
import java.util.List;
import java.util.concurrent.*;
import java.util.concurrent.atomic.AtomicReference;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.embedded.*;
import org.springframework.web.server.ResponseStatusException;
import static org.junit.jupiter.api.Assertions.*;

class AdvisorConcurrencyTest {
 @Test void duplicateRequestsClearDuringGenerationTimeoutAndEmptyResponse() throws Exception {
  var generator=KeyPairGenerator.getInstance("RSA");generator.initialize(2048);var keys=generator.generateKeyPair();
  String pub=Base64.getEncoder().encodeToString(keys.getPublic().getEncoded()),priv=Base64.getEncoder().encodeToString(keys.getPrivate().getEncoded());
  String ticket="Bearer "+new TokenCodec(pub,priv).issue("student");
  var database=new EmbeddedDatabaseBuilder().generateUniqueName(true).setType(EmbeddedDatabaseType.H2).build();var db=new JdbcTemplate(database);
  db.execute("CREATE TABLE user_settings(user_id VARCHAR,advisor_provider VARCHAR,advisor_api_key VARCHAR,advisor_endpoint VARCHAR)");
  db.execute("CREATE TABLE advisor_turns(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,user_id VARCHAR,group_id VARCHAR,question VARCHAR,answer VARCHAR,created_at VARCHAR)");
  db.execute("CREATE TABLE advisor_generations(user_id VARCHAR,group_id VARCHAR,generation BIGINT,PRIMARY KEY(user_id,group_id))");
  db.update("INSERT INTO user_settings(user_id,advisor_provider,advisor_api_key) VALUES('student','test-model','test-key')");
  var server=HttpServer.create(new InetSocketAddress("127.0.0.1",0),0);var executor=Executors.newCachedThreadPool();server.setExecutor(executor);
  var entered=new CountDownLatch(1);var release=new CountDownLatch(1);var mode=new AtomicReference<>("wait");
  server.createContext("/api/v1/group/discussions",exchange->{byte[] body="{\"data\":[]}".getBytes();exchange.sendResponseHeaders(200,body.length);exchange.getResponseBody().write(body);exchange.close();});
  server.createContext("/api/v1/group/members",exchange->{exchange.sendResponseHeaders(200,-1);exchange.close();});
  server.createContext("/model",exchange->{
   try {
    exchange.getRequestBody().readAllBytes();
    if(mode.get().equals("wait")){entered.countDown();release.await(5,TimeUnit.SECONDS);}
    else if(mode.get().equals("timeout"))Thread.sleep(2000);
    byte[] answer=(mode.get().equals("empty")?"{\"choices\":[]}":"{\"choices\":[{\"message\":{\"content\":\"test answer\"}}]}").getBytes();
    exchange.sendResponseHeaders(200,answer.length);exchange.getResponseBody().write(answer);
   }catch(InterruptedException e){Thread.currentThread().interrupt();}finally{exchange.close();}
  });server.start();
  try {
   String base="http://127.0.0.1:"+server.getAddress().getPort();var advisor=new AdvisorController(db,new ObjectMapper(),pub,base+"/model",base,base,1);
   var question=new AdvisorController.Question("group-default","question","share-group-context");
   Future<?> pending=executor.submit(()->advisor.ask(ticket,question));assertTrue(entered.await(3,TimeUnit.SECONDS));
   assertEquals(409,assertThrows(ResponseStatusException.class,()->advisor.ask(ticket,question)).getStatusCode().value());
   advisor.clear(ticket,"group-default");release.countDown();
   var failure=assertThrows(ExecutionException.class,()->pending.get(3,TimeUnit.SECONDS));assertInstanceOf(ResponseStatusException.class,failure.getCause());assertEquals(409,((ResponseStatusException)failure.getCause()).getStatusCode().value());
   assertEquals(0,((List<?>)advisor.history(ticket,"group-default").data()).size());
   mode.set("timeout");assertEquals(502,assertThrows(ResponseStatusException.class,()->advisor.ask(ticket,question)).getStatusCode().value());
   mode.set("empty");assertEquals(502,assertThrows(ResponseStatusException.class,()->advisor.ask(ticket,question)).getStatusCode().value());
   assertEquals(0,((List<?>)advisor.history(ticket,"group-default").data()).size());
   mode.set("success");advisor.ask(ticket,question);assertEquals(1,((List<?>)advisor.history(ticket,"group-default").data()).size());
  }finally{release.countDown();server.stop(0);executor.shutdownNow();database.shutdown();}
 }
}
