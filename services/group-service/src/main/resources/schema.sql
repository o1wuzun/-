CREATE TABLE IF NOT EXISTS members(user_id VARCHAR(36) PRIMARY KEY,nickname VARCHAR(40) NOT NULL,host_name VARCHAR(80) NOT NULL,last_seen BIGINT NOT NULL,revoked BOOLEAN NOT NULL DEFAULT FALSE);
CREATE TABLE IF NOT EXISTS discussions(id VARCHAR(36) PRIMARY KEY,author_id VARCHAR(36) NOT NULL,title VARCHAR(100) NOT NULL,body CLOB NOT NULL,created_at VARCHAR(40) NOT NULL);
CREATE TABLE IF NOT EXISTS comments(id VARCHAR(36) PRIMARY KEY,discussion_id VARCHAR(36) NOT NULL,author_id VARCHAR(36) NOT NULL,body CLOB NOT NULL,created_at VARCHAR(40) NOT NULL,FOREIGN KEY(discussion_id) REFERENCES discussions(id));
CREATE TABLE IF NOT EXISTS event_log(seq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,event_id VARCHAR(36) NOT NULL UNIQUE,kind VARCHAR(80) NOT NULL,payload CLOB NOT NULL,created_at VARCHAR(40) NOT NULL);
CREATE TABLE IF NOT EXISTS replica_nodes(id VARCHAR(36) PRIMARY KEY,user_id VARCHAR(36) NOT NULL,name VARCHAR(80) NOT NULL,credential_hash VARCHAR(64) NOT NULL UNIQUE,revoked BOOLEAN NOT NULL DEFAULT FALSE,last_seen BIGINT NOT NULL);

CREATE TABLE IF NOT EXISTS oj_bindings (
 user_id VARCHAR(36) PRIMARY KEY, provider VARCHAR(30) NOT NULL, handle VARCHAR(80) NOT NULL, version BIGINT NOT NULL,
 FOREIGN KEY(user_id) REFERENCES members(user_id)
);
CREATE TABLE IF NOT EXISTS learning_points (
 id VARCHAR(36) PRIMARY KEY, user_id VARCHAR(36) NOT NULL, title VARCHAR(100) NOT NULL,
 problem_key VARCHAR(40) NOT NULL, criterion VARCHAR(500) NOT NULL, created_at VARCHAR(40) NOT NULL,
 FOREIGN KEY(user_id) REFERENCES members(user_id)
);
CREATE TABLE IF NOT EXISTS daily_checkins (
 id VARCHAR(36) PRIMARY KEY, user_id VARCHAR(36) NOT NULL, learning_day VARCHAR(10) NOT NULL,
 point_id VARCHAR(36) NOT NULL, minutes INT NOT NULL, reflection VARCHAR(2000) NOT NULL,
 verification VARCHAR(30) NOT NULL, evidence_id VARCHAR(80), evidence_handle VARCHAR(80), binding_version BIGINT,
 settled BOOLEAN NOT NULL DEFAULT FALSE, score INT NOT NULL DEFAULT 0, created_at VARCHAR(40) NOT NULL,
 UNIQUE(user_id,learning_day,point_id),
 FOREIGN KEY(user_id) REFERENCES members(user_id), FOREIGN KEY(point_id) REFERENCES learning_points(id)
);
CREATE TABLE IF NOT EXISTS learning_awards (
 user_id VARCHAR(36) NOT NULL, problem_key VARCHAR(40) NOT NULL, checkin_id VARCHAR(36) NOT NULL,
 PRIMARY KEY(user_id,problem_key),
 FOREIGN KEY(user_id) REFERENCES members(user_id), FOREIGN KEY(checkin_id) REFERENCES daily_checkins(id)
);
CREATE INDEX IF NOT EXISTS idx_learning_points_user ON learning_points(user_id,created_at);
CREATE TABLE IF NOT EXISTS learning_plans (
 user_id VARCHAR(36) NOT NULL, learning_day VARCHAR(10) NOT NULL,
 body TEXT NOT NULL, created_at VARCHAR(40) NOT NULL,
 PRIMARY KEY(user_id,learning_day), FOREIGN KEY(user_id) REFERENCES members(user_id)
);

